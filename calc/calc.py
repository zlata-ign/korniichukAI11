print("--- Кулинарный калькулятор ---")
while True:
    a = int(input("Введите первое число: "))
    b = int(input("Введите второе число: "))
    if b == 0:
        print("На ноль делить нельзя! Попробуйте снова. ")
    s = a + b # Сумма (увеличение ингредиентов)
    v = a - b # Вычитание
    p = a * b # Произведение (общая масса)
    d = a / b  # Деление (на порции)
    o = a % b # Остаток продуктов
    st = a ** b # Степень
    cel = a // b # Целочисленное делениеt
    
    print("Сумма:", s)
    print("Вычитание:", v)
    print("Произведение:", p)
    print("Деление:", d)
    print("Остаток:", o)
    print("Степень:", st)
    print("Целочисленное деление:", cel)
    if s > 12:
        print("Получится большая порция блюда")
